    /// Run the REPL loop over scripted input with a
    /// dead gateway; returns the captured stdout.
    fn run_loop(input: &str) -> String {
        let rt = test_runtime();
        let profile = Profile {
            chat_file: temp_path("loop").to_str().unwrap().to_string(),
            ..Default::default()
        };
        let mut inp = Cursor::new(input.as_bytes().to_vec());
        let mut out: Vec<u8> = Vec::new();
        let mut err: Vec<u8> = Vec::new();
        let tokio_rt = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap();
        tokio_rt.block_on(async {
            let mut sess = ChatSession {
                rt: &rt,
                profile: &profile,
                state: ChatState::new(),
                listing: Vec::new(),
                input: &mut inp,
                output: &mut out,
                err_output: &mut err,
                sigint: Arc::new(AtomicBool::new(false)),
                approve_enabled: false,
                allow_once: false,
            };
            sess.repl_loop().await.unwrap();
        });
        String::from_utf8(out).unwrap()
    }

