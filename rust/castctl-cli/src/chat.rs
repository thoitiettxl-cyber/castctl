//! `chat` — the interactive REPL (`internal/commands/chat.go`).
//!
//! Go flow (`cmdChat`, `chat.go:401-478`): `runWaitNetwork`
//! (config → profile → `ensureNodeID` → runtime) → load
//! `chat.json` → EAGER `Connect` (auth failure prints
//! `Can't sign in to muse.ai: <summary>` + the
//! `deliver.AuthExport` guidance to stdout, then exits 2)
//! → banner + `showHistory(3)` → REPL loop → `\nBye.\n`.
//!
//! The REPL core takes injected IO (`&mut dyn BufRead`
//! input, `&mut dyn Write` output + stderr) so the
//! no-network branches are unit-testable with scripted
//! input; production passes the real stdin/stdout/stderr.
//! Chat writes DIRECTLY to the process stdout — the
//! `Ctx` buffering model would hide the prompt until
//! exit, and the prompt must appear immediately (Go
//! `Fprint`s it before each read).
//!
//! Deliberate deviations from Go:
//! - `read_line` blocks one tokio worker thread while
//!   waiting for input. Go blocks its goroutine the same
//!   way; the wait's network work and the Ctrl-C watcher
//!   run on other workers, so nothing stalls. `Ctrl+C`
//!   during a prompt takes effect on the next line (the
//!   `sigint` flag check), exactly like Go's
//!   `ctx.Err()` check after `readLine`.
//! - A chat turn cancels on Ctrl-C via a per-turn
//!   `Cancel` (Go cancels the turn through the root
//!   ctx); the per-line error path then prints
//!   `Connection problem (context canceled). ...` and
//!   continues, like Go.
//! - The eager-connect error path prints the guidance
//!   from `EXPORT_GUIDANCE` (generated byte-exact from
//!   Go) and returns the typed error; the dispatch
//!   renders the typed JSON to stderr, exit 2 —
//!   the same as Go's `runInner`.
//! - `format_updated` maps an out-of-range `updated_at_ms`
//!   to the epoch (chrono has no `time.UnixMilli`
//!   overflow behaviour); real gateway values are
//!   always in range.
//! - Save errors render as `msg(1, <io error text>)`;
//!   Go's `*PathError` text carries the path and the
//!   operation (`mkdir <path>: ...`), Rust's `io::Error`
//!   display does not (dev-21 class).

