/// The turn timeout (`sendOne`: `deliverSend` ack 30s,
/// `executeWait` 300s).
const CHAT_ACK_TIMEOUT: Duration = Duration::from_secs(30);
const CHAT_WAIT_TIMEOUT: Duration = Duration::from_secs(300);

/// `chatState` (`chat.go:62-66`): the persisted last
/// conversation. `session_id` has NO `omitempty`, so the
/// main-chat state writes `"session_id": null`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ChatState {
    pub session_id: Option<String>,
    pub title: String,
}

impl ChatState {
    /// The default state: main chat, no session.
    pub(crate) fn new() -> Self {
        Self {
            session_id: None,
            title: "main chat".to_string(),
        }
    }
}

impl Default for ChatState {
    fn default() -> Self {
        Self::new()
    }
}

/// The on-disk shape, loaded by hand (castctl-cli has
/// no `serde` derive dependency): `session_id` is a
/// string or null, `title` a string; a wrong-typed
/// field is a Go `Unmarshal` error and resets the
/// whole state, like Go. Unknown fields are ignored.
pub(crate) fn load_chat_state(path: &str) -> ChatState {
    let text = match std::fs::read_to_string(path) {
        Ok(t) => t,
        Err(_) => return ChatState::new(),
    };
    let v: SerdeValue = match serde_json::from_str(&text) {
        Ok(v) => v,
        Err(_) => return ChatState::new(),
    };
    let obj = match v.as_object() {
        Some(o) => o,
        None => return ChatState::new(),
    };
    let session_id = match obj.get("session_id") {
        None | Some(SerdeValue::Null) => None,
        Some(SerdeValue::String(s)) => Some(s.clone()),
        Some(_) => return ChatState::new(),
    };
    let title = match obj.get("title") {
        None => String::new(),
        Some(SerdeValue::String(s)) => s.clone(),
        Some(_) => return ChatState::new(),
    };
    let mut st = ChatState { session_id, title };
    if st.title.is_empty() {
        st.title = "main chat".to_string();
    }
    st
}

/// The exact bytes `saveChatState` writes: Go
/// `json.MarshalIndent` (2 spaces, HTML-escaped strings,
/// struct order `session_id`, `title`) + a trailing `\n`.
pub(crate) fn chat_state_json(st: &ChatState) -> String {
    let mut out = String::from("{\n  \"session_id\": ");
    match &st.session_id {
        None => out.push_str("null"),
        Some(s) => out.push_str(&escape_go_marshal_string(s)),
    }
    out.push_str(",\n  \"title\": ");
    out.push_str(&escape_go_marshal_string(&st.title));
    out.push_str("\n}\n");
    out
}

/// `saveChatState` (`chat.go:83-92`): `MkdirAll` the
/// parent at 0700, write the file at 0600 (both modes
/// apply only on creation, in Go and in Rust).
pub(crate) fn save_chat_state(path: &str, st: &ChatState) -> Result<(), FlowErr> {
    use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt};
    let parent = std::path::Path::new(path)
        .parent()
        .map(|p| p.to_path_buf())
        .unwrap_or_default();
    if !parent.as_os_str().is_empty() {
        std::fs::DirBuilder::new()
            .mode(0o700)
            .recursive(true)
            .create(&parent)
            .map_err(|e| msg(1, e.to_string()))?;
    }
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(path)
        .map_err(|e| msg(1, e.to_string()))?;
    f.write_all(chat_state_json(st).as_bytes())
        .map_err(|e| msg(1, e.to_string()))?;
    Ok(())
}

/// `shared.FmtEvent` text (`internal/shared/event.go:50`):
/// the first non-empty of `payload.display_text`,
/// `payload.content`.
pub(crate) fn fmt_event_text(ev: &SerdeValue) -> String {
    let payload = ev.get("payload");
    let display = payload
        .and_then(|p| p.get("display_text"))
        .and_then(|v| v.as_str())
        .unwrap_or("");
    if !display.is_empty() {
        return display.to_string();
    }
    payload
        .and_then(|p| p.get("content"))
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_string()
}

/// `updated_at_ms` rendered as Go
/// `UnixMilli(ms).Local().Format("2006-01-02 15:04")`.
pub(crate) fn format_updated(ms: i64) -> String {
    chrono::DateTime::from_timestamp_millis(ms)
        .unwrap_or_default()
        .with_timezone(&chrono::Local)
        .format("%Y-%m-%d %H:%M")
        .to_string()
}

/// `printWaitTail` with `summary=false` (`wait.go:720`):
/// the needs-input line, one line per approval, the
/// note on stderr. No `-- outcome (status=...)` line.
pub(crate) fn print_wait_tail_text(res: &WaitResult) -> (String, String) {
    let mut out = String::new();
    let mut err = String::new();
    if res.outcome == "needs_input" && !res.question.is_empty() {
        out.push_str(&format!(
            "NEEDS INPUT ({}): {}\n",
            res.needs_input_reason, res.question
        ));
    }
    for a in &res.approvals {
        out.push_str(&format!(
            "NEEDS APPROVAL {}: {} - {}\n",
            a.id, a.title, a.question
        ));
        if !a.why.is_empty() {
            out.push_str(&format!(" why: {}\n", a.why));
        }
    }
    if !res.note.is_empty() {
        err.push_str(&format!("note: {}\n", res.note));
    }
    (out, err)
}

/// Whether the argument is all ASCII digits (Go
/// `isDigits`, used by `/history`).
pub(crate) fn is_digits(s: &str) -> bool {
    !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit())
}

/// `strconv.Atoi(TrimSpace(arg))` for `/open`.
pub(crate) fn parse_chat_number(arg: &str) -> Option<i64> {
    arg.trim().parse::<i64>().ok()
}

/// The REPL's auth check: `classifyConnError`
/// returns a `*typedAuthError` exactly when the
/// `FlowErr` is `Verbatim` with code 2 — the only
/// constructor of that variant is `typed()`
/// (`network.rs:171`).
pub(crate) fn is_auth_flow_err(e: &FlowErr) -> bool {
    matches!(e, FlowErr::Verbatim { code: 2, .. })
}

/// The summary for the per-line error path
/// (`Connection problem (<summary>). ...`): a
/// cancelled turn is `"context canceled"` (Go's
/// `SummarizeErr` on `context.Canceled`, which has no
/// `logSummary`); other errors render their short
/// text. `Exit` / `HelpShown` have no text.
pub(crate) fn connection_problem_summary(e: &FlowErr) -> String {
    if flow_err_code(e) == 130 {
        return "context canceled".to_string();
    }
    flow_err_text(e)
}

/// One REPL session: the runtime, the profile, the
/// persisted state, the last `/chats` listing, and
/// the injected IO. `chat.go:95-102`.
pub(crate) struct ChatSession<'a> {
    rt: &'a Runtime,
    profile: &'a Profile,
    state: ChatState,
    listing: Vec<SerdeValue>,
    input: &'a mut dyn BufRead,
    output: &'a mut dyn Write,
    err_output: &'a mut dyn Write,
    sigint: Arc<AtomicBool>,
    approve_enabled: bool,
    allow_once: bool,
}

impl<'a> ChatSession<'a> {
    /// The current scope: the thread's session id, or
    /// `""` for the main chat (`chat.go:104-110`).
    pub(crate) fn scope(&self) -> &str {
        self.state.session_id.as_deref().unwrap_or("")
    }

    /// `messages` (`chat.go:119-160`): `chat.history`
    /// `{limit, session_id?}` on the shared connection,
    /// sorted by `seq` ascending (stable), keeping only
    /// `message.user` / `message.assistant` events with
    /// non-empty `FmtEvent` text.
    pub(crate) async fn messages(&mut self, limit: i64) -> Result<Vec<(String, String)>, FlowErr> {
        let scope = self.scope().to_string();
        let mut body = serde_json::Map::new();
        body.insert("limit".to_string(), SerdeValue::from(limit));
        if !scope.is_empty() {
            body.insert("session_id".to_string(), SerdeValue::from(scope));
        }
        let v = call_map(
            self.rt,
            "chat.history",
            RequestOptions {
                body: Body::Json(SerdeValue::Object(body)),
                ..Default::default()
            },
        )
        .await?;
        let mut events: Vec<SerdeValue> = v
            .get("chat_events")
            .and_then(|e| e.as_array())
            .cloned()
            .unwrap_or_default();
        events.sort_by_key(event_seq);
        let mut out = Vec::new();
        for ev in &events {
            let name = ev.get("event_name").and_then(|n| n.as_str()).unwrap_or("");
            let who = match name {
                "message.user" => "You",
                "message.assistant" => "Muse",
                _ => continue,
            };
            let text = fmt_event_text(ev);
            if text.is_empty() {
                continue;
            }
            out.push((who.to_string(), text));
        }
        Ok(out)
    }

    /// `showHistory` (`chat.go:162-178`): `messages(n*3)`,
    /// keep the last n; none → `No messages here yet.`.
    pub(crate) async fn show_history(&mut self, n: i64) -> Result<(), FlowErr> {
        let msgs = self.messages(n.wrapping_mul(3)).await?;
        let tail: Vec<(String, String)> = if (msgs.len() as i64) > n {
            msgs[msgs.len() - (n as usize)..].to_vec()
        } else {
            msgs
        };
        if tail.is_empty() {
            let _ = writeln!(self.output, "No messages here yet.");
        } else {
            for (who, text) in &tail {
                let _ = writeln!(self.output, "\n{who}: {text}");
            }
        }
        Ok(())
    }

    /// `listChats` (`chat.go:180-224`): `sessions.list`
    /// `{}` on the shared connection; archived sessions
    /// are skipped; the listing is stored for `/open`.
    pub(crate) async fn list_chats(&mut self) -> Result<(), FlowErr> {
        let v = call_map(self.rt, "sessions.list", RequestOptions::default()).await?;
        let sessions: Vec<SerdeValue> = v
            .get("sessions")
            .and_then(|s| s.as_array())
            .cloned()
            .unwrap_or_default();
        self.listing = sessions
            .into_iter()
            .filter(|s| s.as_object().is_some())
            .filter(|s| !s.get("archived").and_then(|a| a.as_bool()).unwrap_or(false))
            .collect();
        for (i, sess) in self.listing.iter().enumerate() {
            let title = sess.get("title").and_then(|t| t.as_str()).unwrap_or("");
            let title = if title.is_empty() { "untitled" } else { title };
            let is_thread = sess
                .get("is_thread")
                .and_then(|t| t.as_bool())
                .unwrap_or(false);
            let main = if is_thread { "" } else { " (main chat)" };
            let ms = sess
                .get("updated_at_ms")
                .and_then(|v| v.as_number())
                .and_then(|n| n.as_str().parse::<i64>().ok())
                .unwrap_or(0);
            let _ = writeln!(
                self.output,
                "{}. {}{}, updated {}",
                i + 1,
                title,
                main,
                format_updated(ms)
            );
        }
        let _ = writeln!(self.output, "Type /open and a number to switch.");
        Ok(())
    }

    /// `switchTo` (`chat.go:226-233`): replace the state,
    /// save it, print `Now in: <title>`, then
    /// `showHistory(3)`.
    pub(crate) async fn switch_to(
        &mut self,
        session_id: Option<String>,
        title: String,
    ) -> Result<(), FlowErr> {
        self.state = ChatState {
            session_id,
            title: title.clone(),
        };
        save_chat_state(&self.profile.chat_file, &self.state)?;
        let _ = writeln!(self.output, "Now in: {title}");
        self.show_history(3).await
    }

    /// `openChat` (`chat.go:235-262`): an empty listing
    /// lists first and RETURNS (it does not continue to
    /// open); an unparsable number or an out-of-range
    /// number prints a hint and stays.
    pub(crate) async fn open_chat(&mut self, arg: &str) -> Result<(), FlowErr> {
        if self.listing.is_empty() {
            return self.list_chats().await;
        }
        let n = match parse_chat_number(arg) {
            Some(n) => n,
            None => {
                let _ = writeln!(self.output, "Type /open and a number from /chats.");
                return Ok(());
            }
        };
        if n < 1 || n as usize > self.listing.len() {
            let _ = writeln!(
                self.output,
                "No conversation with that number. Type /chats to see them."
            );
            return Ok(());
        }
        let sess = &self.listing[(n - 1) as usize];
        let id = sess
            .get("session_id")
            .and_then(|s| s.as_str())
            .unwrap_or("");
        let session_id = if id.is_empty() {
            None
        } else {
            Some(id.to_string())
        };
        let title = sess.get("title").and_then(|t| t.as_str()).unwrap_or("");
        let title = if title.is_empty() {
            "untitled".to_string()
        } else {
            title.to_string()
        };
        self.switch_to(session_id, title).await
    }

    /// `newChat` (`chat.go:264-290`): `session.start`
    /// with the title, then `switchTo` (the display
    /// title defaults to `new conversation`).
    pub(crate) async fn new_chat(&mut self, title: &str) -> Result<(), FlowErr> {
        let v = crate::network::session_start_call(self.rt, title).await?;
        let session_id = v.as_object().and_then(|o| {
            o.get("session_id")
                .or_else(|| o.get("id"))
                .and_then(|s| s.as_str())
                .filter(|s| !s.is_empty())
                .map(|s| s.to_string())
        });
        let display = if title.is_empty() {
            "new conversation".to_string()
        } else {
            title.to_string()
        };
        self.switch_to(session_id, display).await
    }
}

impl<'a> ChatSession<'a> {
    /// `sendOne` (`chat.go:292-324`): `deliverSend` (ack
    /// 30s) on a fresh lease kept open for the whole
    /// turn; a nil ack prints the no-ack note and stays
    /// in the REPL; else `Muse is thinking...`,
    /// `executeWait` (300s, no toggles — resolved from
    /// env/profile), one `\nMuse: <text>\n` per reply,
    /// the tail (summary=false), and the timeout hint.
    pub(crate) async fn send_one(&mut self, text: &str) -> Result<(), FlowErr> {
        // Go cancels the turn through the root ctx on
        // Ctrl-C; here a per-turn `Cancel` wired to a
        // ctrl_c watcher plays that role.
        let cancel = Cancel::new();
        let sig_cancel = cancel.clone();
        tokio::spawn(async move {
            if tokio::signal::ctrl_c().await.is_ok() {
                sig_cancel.set();
            }
        });
        let (user_seq, _) = deliver_send(
            self.rt,
            self.profile,
            text,
            self.scope(),
            CHAT_ACK_TIMEOUT,
            &cancel,
        )
        .await?;
        let Some(user_seq) = user_seq else {
            let _ = writeln!(
                self.output,
                "no delivery ack within 30s; check `castctl history`"
            );
            return Ok(());
        };
        let _ = writeln!(self.output, "Muse is thinking...");
        let (res, _enabled, auto_stderr) = execute_wait(
            self.rt,
            self.profile,
            self.scope(),
            Some(user_seq),
            CHAT_WAIT_TIMEOUT,
            self.approve_enabled,
            self.allow_once,
        )
        .await?;
        // Go's `executeWait` writes the auto-approved
        // lines directly to env.stderr during the wait;
        // the Rust side returns them as a string.
        let _ = write!(self.err_output, "{auto_stderr}");
        for r in &res.replies {
            let _ = writeln!(self.output, "\nMuse: {}", r.text);
        }
        let (tail_out, tail_err) = print_wait_tail_text(&res);
        let _ = write!(self.output, "{tail_out}");
        let _ = write!(self.err_output, "{tail_err}");
        if res.outcome == "timeout" {
            let _ = writeln!(
                self.output,
                "(No reply within 300 seconds. Type /history later to check.)"
            );
        }
        Ok(())
    }

    /// `handle` (`chat.go:326-384`): one slash command.
    /// `/login` prints the `deliver.AuthExport`
    /// guidance (the `"Signed in."` branch is
    /// unreachable — `AuthExport` always returns an
    /// `ExportError`).
    pub(crate) async fn handle(&mut self, line: &str) -> Result<(), FlowErr> {
        let (cmd, rest) = match line.split_once(' ') {
            Some((c, r)) => (c, r.trim()),
            None => (line, ""),
        };
        match cmd {
            "/help" | "/?" => {
                let _ = writeln!(self.output, "{CHAT_HELP_TEXT}");
            }
            "/chats" => {
                self.list_chats().await?;
            }
            "/open" => {
                self.open_chat(rest).await?;
            }
            "/main" => {
                self.switch_to(None, "main chat".to_string()).await?;
            }
            "/new" => {
                self.new_chat(rest).await?;
            }
            "/history" => {
                let mut n = 10i64;
                if is_digits(rest) {
                    n = rest.parse::<i64>().unwrap_or(n);
                }
                self.show_history(n).await?;
            }
            "/login" => {
                // Raw on purpose: Go prints the guidance to chat
                // stdout (`chat.go:352`, `Fprintln(stdout,
                // Guidance)`), NOT through `classifyError` — only
                // the `auth export` stderr path is `SafeString`d
                // (M7f fix loop 1, B1).
                let _ = writeln!(self.output, "{EXPORT_GUIDANCE}");
            }
            _ => {
                let _ = writeln!(self.output, "Unknown command. Type /help.");
            }
        }
        Ok(())
    }

    /// `readLine` (`chat.go:386-399`): print the prompt
    /// (flushed — it ends with a space, not a newline)
    /// and read one line from the persistent reader.
    /// `None` is EOF: an empty read, or a partial line
    /// without a trailing `\n` (Go's `ReadString`
    /// returns the partial line WITH `io.EOF`, and
    /// `cmdChat` breaks without processing it).
    pub(crate) fn read_line(&mut self) -> Result<Option<String>, FlowErr> {
        let _ = write!(self.output, "\nYou: ");
        let _ = self.output.flush();
        let mut buf = Vec::new();
        let n = self
            .input
            .read_until(b'\n', &mut buf)
            .map_err(|e| msg(1, e.to_string()))?;
        if n == 0 {
            return Ok(None);
        }
        if !buf.ends_with(b"\n") {
            return Ok(None);
        }
        let line = String::from_utf8_lossy(&buf);
        Ok(Some(line.trim_end_matches(['\r', '\n']).to_string()))
    }

    /// The REPL loop (`cmdChat` `chat.go:448-474`): read,
    /// skip empty lines, break on an exit command or on
    /// the SIGINT flag (Go's `ctx.Err()` check, after
    /// the exit-command check), dispatch slash commands
    /// to `handle` and anything else to `send_one`.
    /// A per-line error is NOT fatal: an auth failure
    /// prints `Your login expired. ...` and continues;
    /// any other error prints `Connection problem
    /// (<summary>). Reconnected; please try again.` and
    /// drops the connection (Go's `rt.Muse.Close()` =
    /// `StopHeartbeat` + `Reset`), then continues.
    pub(crate) async fn repl_loop(&mut self) -> Result<(), FlowErr> {
        while let Some(line) = self.read_line()? {
            let line = line.trim().to_string();
            if line.is_empty() {
                continue;
            }
            let lower = line.to_lowercase();
            if lower == "/exit" || lower == "/quit" || lower == "exit" || lower == "quit" {
                break;
            }
            if self.sigint.load(Ordering::SeqCst) {
                break;
            }
            let run_err = if line.starts_with('/') {
                self.handle(&line).await
            } else {
                self.send_one(&line).await
            };
            if let Err(e) = run_err {
                if is_auth_flow_err(&e) {
                    let _ = writeln!(
                        self.output,
                        "Your login expired. Type /login to sign in again."
                    );
                    continue;
                }
                let _ = writeln!(
                    self.output,
                    "Connection problem ({}). Reconnected; please try again.",
                    connection_problem_summary(&e)
                );
                self.rt.shared.stop_heartbeat().await;
                if let Some(gw) = self.rt.shared.snapshot() {
                    self.rt.shared.drop_gateway(&gw).await;
                }
            }
        }
        Ok(())
    }

    /// The banner, `showHistory(3)`, the loop, and
    /// `\nBye.\n` (`cmdChat` `chat.go:440-477`).
    pub(crate) async fn run_repl(&mut self) -> Result<(), FlowErr> {
        let _ = writeln!(
            self.output,
            "Muse chat, in: {}. Type /help for commands, /exit to quit.",
            self.state.title
        );
        self.show_history(3).await?;
        self.repl_loop().await?;
        let _ = writeln!(self.output, "\nBye.");
        Ok(())
    }
}

/// `cmdChat` (`chat.go:401-478`): `runWaitNetwork`
/// (config → profile → `ensureNodeID` → runtime),
/// load `chat.json`, eager-connect (auth failure prints
/// the guidance to stdout and exits 2), then the REPL.
/// Chat has no flags and no positionals (`run_inner`
/// already defaults an empty command name to `"chat"`).
/// Writes directly to the process stdout/stderr —
//  the `Ctx` out streams stay empty (the prompt must
/// appear immediately).
pub(crate) fn run_chat_command(
    ctx: &mut Ctx<'_>,
    g: &GlobalOpts,
    _p: &Parsed,
) -> Result<(), FlowErr> {
    let (loc, single) = resolve_and_load_single(ctx, g)?;
    let profile_flag = if g.profile_set {
        Some(g.profile_flag.as_str())
    } else {
        None
    };
    let getenv = ctx.getenv;
    let mut profile =
        resolve_active_profile(&loc.config_dir, profile_flag, getenv).map_err(config_err)?;
    ensure_node_id(&mut profile, lookup_env(ctx, "MUSE_NODE_ID"));
    let approve_enabled =
        resolve_auto_approve(&profile, None, lookup_env(ctx, "MUSE_AUTO_APPROVE"))?;
    let allow_once =
        resolve_auto_allow_once(&profile, None, lookup_env(ctx, "MUSE_AUTO_ALLOW_ONCE"))?;
    let tokio_rt = tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .build()
        .map_err(|e| msg(1, e.to_string()))?;
    tokio_rt.block_on(async move {
        let runtime = build_runtime(&loc, single.as_ref(), profile_flag, getenv)?;
        // Go's root ctx comes from `signal.NotifyContext`
        // (`cmd/castctl/main.go:36`); the loop checks the
        // flag after each `readLine`.
        let sigint = Arc::new(AtomicBool::new(false));
        let sig_watch = Arc::clone(&sigint);
        tokio::spawn(async move {
            if tokio::signal::ctrl_c().await.is_ok() {
                sig_watch.store(true, Ordering::SeqCst);
            }
        });
        // Eager connect: Go does `rt.Muse.Connect(ctx,
        // nil)` then `Close()`; the shared connection
        // stays up for the session here.
        if let Err(te) = runtime.shared.live().await {
            let fe = classify_conn_error(&te);
            if is_auth_flow_err(&fe) {
                let summary = match &te {
                    TransportError::Auth { message } => auth_summary(message),
                    TransportError::Gateway(summary) => gateway_error_text(summary),
                    _ => String::new(),
                };
                let stdout = std::io::stdout();
                let mut out = stdout.lock();
                let _ = writeln!(out, "Can't sign in to muse.ai: {summary}");
                let _ = writeln!(out, "{EXPORT_GUIDANCE}");
                let _ = out.flush();
            }
            return Err(fe);
        }
        let state = load_chat_state(&profile.chat_file);
        let stdin = std::io::stdin();
        let mut input = stdin.lock();
        let stdout = std::io::stdout();
        let mut output = stdout.lock();
        let stderr = std::io::stderr();
        let mut err_output = stderr.lock();
        let mut sess = ChatSession {
            rt: &runtime,
            profile: &profile,
            state,
            listing: Vec::new(),
            input: &mut input,
            output: &mut output,
            err_output: &mut err_output,
            sigint,
            approve_enabled,
            allow_once,
        };
        sess.run_repl().await
    })
}

