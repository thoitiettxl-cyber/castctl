// MigrateProfile is one profile in a MigrateResult.
type MigrateProfile struct {
	Name string `json:"name"`
	// Source is "legacy" for profiles built from the old layout and
	// "single" for profiles carried over verbatim from an existing
	// single file (NB4: single-file-only profiles).
	Source string `json:"source"`
	// CookiesFile is the resolved cookies file path.
	CookiesFile string `json:"cookies_file"`
	// Outbound is always nil (null) for migrated profiles: migration
	// never invents an outbound.
	Outbound *OutboundRef `json:"outbound"`
	// Warnings lists non-fatal observations, e.g. a missing cookies
	// file or a generated node_id. Warning text never contains secret
	// values.
	Warnings []string `json:"warnings"`
	// NodeIDGenerated reports that a node_id was generated for this
	// profile (write mode only; dry-run never invents one).
	NodeIDGenerated bool `json:"node_id_generated,omitempty"`
}

// MigrateResult is the JSON-marshalable result of Migrate. The caller
// decides the exit code from the returned error: any profile error or
// a refuse-overwrite produces a non-nil error, but the result still
// lists the good profiles that would migrate.
type MigrateResult struct {
	// SourceDir is the directory legacy profiles were read from.
	SourceDir string `json:"source_dir"`
	// DestinationDir is the directory the single config was (or
	// would be) written to.
	DestinationDir string `json:"destination_dir"`
	// WouldWrite reports whether a dry-run would write a file. False
	// after migration (already-migrated) and when overwriting is refused.
	WouldWrite bool `json:"would_write"`
	// Migrated reports whether this call wrote the single file.
	Migrated bool `json:"migrated"`
	// Reason is "already-migrated", "refuse-overwrite",
	// "dns-authored" (a run that wrote only the interim dns section
	// onto an otherwise already-migrated config), or
	// "dns-distributed" (a run that distributed the top-level dns
	// section into profile entries and removed it) when applicable.
	Reason               string           `json:"reason,omitempty"`
	DefaultProfile       string           `json:"default_profile"`
	Profiles             []MigrateProfile `json:"profiles"`
	ExistingSingleConfig bool             `json:"existing_single_config"`
	// Errors lists per-profile error messages (no secret values).
	Errors []string `json:"errors"`
	// Generated lists profile names whose node_id was generated by
	// this write. Never populated by a dry-run.
	Generated []string `json:"generated,omitempty"`
	// DNSAuthored reports that this run authored the interim global
	// dns section (see authorInterimDNS). It is set only when the
	// candidate had no dns section and every profile shared one
	// outbound tag to detour through.
	DNSAuthored bool `json:"dns_authored,omitempty"`
	// DNSRefusal records why no dns section was authored, naming
	// the profile that has no single detour (or the validation
	// failure). It is informational: the migration itself still
	// succeeds and writes no dns section. Empty when a dns section
	// was carried verbatim, authored, or not applicable.
	DNSRefusal string `json:"dns_refusal,omitempty"`
	// DNSDistributed reports that this run distributed the
	// top-level dns section into every profile's own dns block
	// and removed the top-level key (see distributeTopLevelDNS).
	// It is set only when a legacy top-level section was
	// present and distribution succeeded.
	DNSDistributed bool `json:"dns_distributed,omitempty"`
	// DNSDistributionRefusal records why distribution of the
	// top-level dns section refused, naming the profile and the
	// failing field/tag. Unlike DNSRefusal it accompanies a
	// returned error: a refused distribution writes nothing
	// and exits 2. Empty when distribution succeeded or was
	// not applicable.
	DNSDistributionRefusal string `json:"dns_distribution_refusal,omitempty"`
}

// Migrate migrates the legacy layout in baseDir into baseDir's
// single config. It is MigrateFrom with source == destination.
func Migrate(baseDir string, write bool) (*MigrateResult, error) {
	return MigrateFrom(baseDir, baseDir, write)
}

// MigrateFrom implements `config migrate` as a library function.
// With write=false it is a dry-run: it prints
// nothing and writes no files. With write=true it writes the single
// file atomically (0600) and never deletes or modifies any old file.
//
//   - A second run over identical parsed content returns
//     {migrated:false, reason:"already-migrated"} with no error.
//     Profiles present only in the single file (no legacy layout),
//     and the file's outbounds/endpoints/dns/default_profile, are
//     carried over verbatim (NB4), so a single-file-only layout is
//     already-migrated on the first run too; comparison happens
//     before any node_id generation.
//   - A different existing single file is a refuse-overwrite error:
//     migrate is one-shot and has no --overwrite; later profiles are
//     added via profile-add, not migrate.
//   - Fingerprint and tls_engine values present in a profile entry
//     or legacy file are preserved verbatim; absent keys stay at
//     their defaults (and stay absent in the written file).
//   - A missing node_id is generated with crypto/rand (16 hex chars)
//     only in write mode, listed in Generated, and never written back
//     to old files.
//   - Any profile error is an overall error, but the result still
//     lists the good profiles; in write mode nothing is written when
//     any profile error exists (all-or-nothing).
//   - DNS extension (interim global section only): when the
//     candidate has no dns section, authorInterimDNS authors the
//     gated default DoH section only if every profile shares one
//     outbound tag to detour through, and only onto a config that
//     is otherwise already-migrated. Otherwise it records the
//     refusal (DNSRefusal, naming the profile) and writes no dns
//     section; the migration itself still succeeds. A fresh
//     legacy migration is always direct-only, so it always
//     records a refusal: there is no outbound tag to detour
//     through until an outbound is supplied separately.
//   - DNS distribution (G4): when the existing single file
//     carries a top-level dns section, distributeTopLevelDNS
//     copies it verbatim into every profile's own dns block
//     (detours filled/kept/refused per profile) and removes
//     the top-level key in the same atomic write, again only
//     onto an otherwise already-migrated config. A refusal
//     (unreachable detour, WireGuard-shadowed profile, invalid
//     distributed candidate) is an error: exit 2, nothing is
//     written, and the refusal is recorded in
//     DNSDistributionRefusal.
//   - A fresh migration over a destination file with no
//     "profiles" key that carries single-format sections in
//     single-config shape (see refuseSingleFormatBaseFile)
//     refuses with exit 2 and writes nothing, instead of
//     overwriting the file and deleting those sections.
//   - Migrate reads files only: it does not consult MUSE_VM_ID /
//     MUSE_NODE_ID (env fill happens at Load time), and touches no
//     telegram or update files.
//
// MigrateFrom migrates legacy profiles from sourceDir into the single
// config in destDir (`config migrate --from`). The source directory
// is read-only: it is never written, locked, or modified in any way,
// and legacy files there keep serving as the backup. The destination
// holds the config lock in write mode, the refuse-overwrite decision,
// and the atomic 0600 write. When sourceDir == destDir (compared
// after resolving symlinks, so a symlink alias of the destination
// counts as the destination itself) behaviour is exactly Migrate's.
// When they differ, the source directory must exist and be a directory, else
// the run is an exit-2 error that writes nothing; a single-format
// file in the source is not copied — the strict legacy parser
// refuses it as a profile error, like any other non-legacy source
// content. Cookies files stay where they are: migrated entries point
// at the source cookies files by absolute path.
func MigrateFrom(sourceDir, destDir string, write bool) (*MigrateResult, error) {
	result := &MigrateResult{
		SourceDir:      sourceDir,
		DestinationDir: destDir,
		Profiles:       []MigrateProfile{},
		Errors:         []string{},
	}
	if destDir == "" {
		return result, newConfigError("migrate: destination directory must not be empty")
	}
	if sourceDir == "" {
		sourceDir = destDir
		result.SourceDir = destDir
	}
	same := sameDir(sourceDir, destDir)
	if same {
		// An alias spelling of the destination takes same-dir
		// behaviour exactly: every later path (discovery,
		// cookies defaults, the written config) uses the
		// destination spelling, so the run is byte-identical
		// to one invoked without --from.
		sourceDir = destDir
		result.SourceDir = destDir
	}
	if !same {
		info, serr := os.Stat(sourceDir)
		if serr != nil {
			if os.IsNotExist(serr) {
				return result, newConfigErrorf("migrate: source directory %q does not exist", sourceDir)
			}
			return result, newConfigErrorf("migrate: cannot stat source directory %q: %v", sourceDir, serr)
		}
		if !info.IsDir() {
			return result, newConfigErrorf("migrate: source %q is not a directory", sourceDir)
		}
	}

	// Write mode holds the config lock across the WHOLE
	// decide+write (RT-2): the already-migrated/refuse
	// decision, the node_id generation, and the write all
	// happen under one lock acquisition, re-reading the
	// current single file under the lock. Without this, two
	// concurrent `migrate --write` runs both decided on the
	// absent file, both generated different node_ids, and
	// both exited 0 with the last write winning — the other
	// run reported ids that were never persisted — and a
	// concurrent `profile add` could be clobbered by the
	// stale-candidate write. Under the lock the second
	// migrate re-reads the file the first one wrote and
	// reports already-migrated, and an add serialises either
	// before (carried over verbatim, NB4) or after the
	// migrate. The write below therefore uses
	// writeSingleConfigLocked directly: SaveSingleConfig
	// would re-acquire the lock and deadlock. Migrate must
	// not be called from inside an UpdateSingleConfig update
	// function (the lock is already held there). Dry-run
	// takes no lock: it reads only. The lock is always the
	// DESTINATION's: the source is read-only and needs none.
	if write {
		release, err := lockConfigDir(destDir)
		if err != nil {
			return result, err
		}
		defer release()
	}

	existing, existingIsSingle, malformedErr, err := readExistingSingle(destDir)
	if err != nil {
		return result, err
	}
	if malformedErr != nil && !same {
		// A malformed destination file is not a legacy source
		// profile error: refuse to overwrite it blindly.
		return result, malformedErr
	}
	result.ExistingSingleConfig = existingIsSingle

	// Discover legacy profiles: default first, then sorted dir names.
	names, err := DiscoverProfileNames(sourceDir)
	if err != nil {
		return result, err
	}
	sort.Strings(names[1:])

	// profiles/default/config.json is a legacy file for the
	// default profile (R4): directory discovery skips a directory
	// named "default", so its presence is detected explicitly
	// (Stat only; the read guard in migrateLegacyProfile refuses
	// a non-regular file without opening it).
	strayPath := strayDefaultLegacyPath(sourceDir)
	_, strayStatErr := os.Stat(strayPath)
	strayPresent := strayStatErr == nil

	// NB4: when a single file already exists it wins wholly. Its
	// entries are carried over verbatim (cloned) first, including
	// profiles present ONLY in the single file: DiscoverProfileNames
	// only sees directories, so single-only names never appear in
	// `names` and were previously dropped, making every second run
	// refuse-overwrite. Legacy files are then consulted only for
	// profiles absent from the single file — except cross-dir
	// (--from): a source legacy file for a name already in the
	// single file is still read and compared (identical stands,
	// differing refuses; see the fromSingle branch below).
	candidateProfiles := []*Profile{}
	fromSingle := make(map[string]bool)
	if existingIsSingle {
		for _, name := range singleFirstNames(existing.ProfileNames()) {
			candidateProfiles = append(candidateProfiles, existing.Profiles[name].clone())
			fromSingle[name] = true
		}
	}
	profileErrors := []string{}
	// A symlinked profile directory whose target cannot be resolved
	// holds no readable legacy file, but it must not vanish silently
	// from a migration: fail the run naming the path, so the
	// operator removes it or restores its target. (Discovery above
	// skips it; only the migration step fails loudly, so list/load
	// stay lenient about stale links.)
	if entries, rerr := os.ReadDir(filepath.Join(sourceDir, "profiles")); rerr == nil {
		for _, e := range entries {
			if e.Type()&os.ModeSymlink == 0 {
				continue
			}
			linkPath := filepath.Join(sourceDir, "profiles", e.Name())
			if st, serr := os.Stat(linkPath); serr != nil {
				profileErrors = append(profileErrors, fmt.Sprintf("symlinked profile dir %q cannot be resolved: %v; migrate cannot read it (remove it or restore its target)", linkPath, serr))
			} else if !st.IsDir() {
				// A symlink resolving to a regular file (not a
				// directory) holds no profile directory to read,
				// but it must not vanish silently either:
				// discovery requires IsDir, so without this
				// check the entry would be dropped with rc=0
				// (and a profiles/default link would be
				// replaced by a synthetic default).
				profileErrors = append(profileErrors, fmt.Sprintf("symlinked profile dir %q is not a directory (it resolves to a non-directory); migrate cannot read it as a profile directory (remove it or restore it to a directory)", linkPath))
			}
		}
	}
	for _, name := range names {
		paths, perr := ProfilePaths(sourceDir, name)
		if perr != nil {
			profileErrors = append(profileErrors, perr.Error())
			continue
		}
		if malformedErr != nil && same && name == DefaultProfileName {
			// The base config.json is malformed JSON: record it once
			// as the default profile's error; do not re-read it as a
			// legacy file. (Only when source == destination: the
			// malformed file IS the source base file. A malformed
			// destination file with a separate source is refused
			// above, before discovery.)
			profileErrors = append(profileErrors, malformedErr.Error())
			continue
		}
		if name == DefaultProfileName && strayPresent {
			// The stray default legacy file migrates like any
			// named legacy file: its settings become the default
			// entry. It is never silently dropped.
			strayDir := filepath.Dir(strayPath)
			strayPaths := Paths{
				Dir:     strayDir,
				Config:  strayPath,
				Cookies: filepath.Join(strayDir, "cookies.txt"),
				Chat:    filepath.Join(strayDir, "chat.json"),
			}
			strayProfile, serr := migrateLegacyProfile(sourceDir, name, strayPaths)
			if serr != nil {
				profileErrors = append(profileErrors, serr.Error())
				continue
			}
			// A legacy base file as well means two legacy files
			// claim the default profile: refuse naming both
			// instead of choosing one. (When source == destination
			// and a single file exists, the base file IS the single
			// file, so it does not count here.)
			baseLegacy := false
			if !(same && existingIsSingle) {
				if configPathExists(filepath.Join(sourceDir, "config.json")) {
					baseLegacy = true
				}
			}
			if baseLegacy {
				profileErrors = append(profileErrors, fmt.Sprintf("profile %q has two legacy config files: %q and %q; refusing to choose between them (remove one, or migrate one by hand)", name, filepath.Join(sourceDir, "config.json"), strayPath))
				continue
			}
			if existingIsSingle && fromSingle[name] {
				// The destination already has a default entry:
				// identical settings stand as already-migrated;
				// differing settings are a collision naming
				// both locations, never a silent skip.
				if legacyProfileSettingsEqual(strayProfile, existing.Profiles[name]) {
					continue
				}
				profileErrors = append(profileErrors, fmt.Sprintf("profile %q differs between source legacy file %q and destination config %q; refusing to overwrite", name, strayPath, filepath.Join(destDir, "config.json")))
				continue
			}
			candidateProfiles = append(candidateProfiles, strayProfile)
			continue
		}
		if existingIsSingle {
			if fromSingle[name] {
				if !same && configPathExists(paths.Config) {
					// Cross-dir collision: the source holds
					// a legacy file for a name the
					// destination already has. Identical
					// settings stand as already-migrated;
					// differing settings refuse, naming
					// the profile and both locations — never
					// a silent skip, which would drop the
					// source settings without a trace. A
					// bare source directory with no config
					// file for the name has nothing to
					// compare and stays silent. Same-dir
					// behaviour is unchanged (NB4): the
					// single file wins wholly, without
					// reading the legacy file.
					srcProfile, serr := migrateLegacyProfile(sourceDir, name, paths)
					if serr != nil {
						profileErrors = append(profileErrors, serr.Error())
						continue
					}
					if !legacyProfileSettingsEqual(srcProfile, existing.Profiles[name]) {
						profileErrors = append(profileErrors, fmt.Sprintf("profile %q differs between source legacy file %q and destination config %q; refusing to overwrite", name, paths.Config, filepath.Join(destDir, "config.json")))
						continue
					}
				}
				continue
			}
			if name == DefaultProfileName && same {
				// The base config.json IS the single file; the
				// default profile has no separate legacy file,
				// and it is absent from the single file, so
				// there is no default entry to carry over.
				// With a separate source dir, the source base
				// file IS a separate legacy file and migrates
				// like any named profile (no skip).
				continue
			}
		}
		p, perr := migrateLegacyProfile(sourceDir, name, paths)
		if perr != nil {
			profileErrors = append(profileErrors, perr.Error())
			continue
		}
		candidateProfiles = append(candidateProfiles, p)
	}

	// Generate missing node_ids only in write mode and only when
	// there is no existing single file: an already-migrated file is
	// compared verbatim (NB4) before any generation, so a second run
	// never invents an id for a profile already in the single file,
	// and a refused run never reports ids it did not write.
	generated := []string{}
	if write && !existingIsSingle {
		for _, p := range candidateProfiles {
			if !p.nodeIDPresent || p.NodeID == "" {
				id, gerr := generateNodeID()
				if gerr != nil {
					return result, gerr
				}
				p.NodeID = id
				p.nodeIDPresent = true
				generated = append(generated, p.Name)
			}
		}
	}

	// The effective default_profile reported in the result; the
	// candidate file itself reuses the existing value verbatim (even
	// when absent) so comparison against an existing file is exact.
	effectiveDefault := DefaultProfileName
	if existingIsSingle && existing.DefaultProfile != "" {
		effectiveDefault = existing.DefaultProfile
	}
	result.DefaultProfile = effectiveDefault
	generatedSet := make(map[string]bool, len(generated))
	for _, g := range generated {
		generatedSet[g] = true
	}
	for _, p := range candidateProfiles {
		source := "legacy"
		if fromSingle[p.Name] {
			source = "single"
		}
		mp := MigrateProfile{
			Name:            p.Name,
			Source:          source,
			CookiesFile:     p.CookiesFile,
			Outbound:        nil,
			Warnings:        migrateWarnings(p, write, generatedSet),
			NodeIDGenerated: generatedSet[p.Name],
		}
		if mp.Warnings == nil {
			mp.Warnings = []string{}
		}
		result.Profiles = append(result.Profiles, mp)
	}
	result.Generated = generated
	if len(profileErrors) > 0 {
		result.Errors = append(result.Errors, profileErrors...)
		return result, newConfigErrorf("migrate: %d profile error(s)", len(profileErrors))
	}

	var candidate *SingleConfig
	if existingIsSingle {
		// Carry the existing file's outbounds, endpoints, dns, and
		// default_profile verbatim (NB4); only legacy-only profiles
		// are added.
		candidate = cloneSingleConfig(existing)
		for _, p := range candidateProfiles {
			if !fromSingle[p.Name] {
				candidate.Profiles[p.Name] = p
			}
		}
	} else {
		candidate = &SingleConfig{
			DefaultProfile: DefaultProfileName,
			Profiles:       make(map[string]*Profile),
		}
		for _, p := range candidateProfiles {
			candidate.Profiles[p.Name] = p
		}
	}

	if existingIsSingle {
		// G4 distribution: when the existing file carries a
		// top-level dns section, distribute it verbatim into
		// every profile's own dns block and remove the top-level
		// key in the same atomic write — but only onto a config
		// that is otherwise already-migrated (the
		// authorInterimDNS gate: the distribution diff must be
		// exactly the dns move, nothing else). A differing
		// config falls through to refuse-overwrite below, with
		// no distribution attempted. A distribution refusal
		// (no profile to receive a block, unreachable detour,
		// WireGuard-shadowed profile, or an invalid distributed
		// candidate) is an error: the whole run refuses,
		// exit 2, nothing is written.
		if candidate.DNS != nil {
			otherwiseMigrated, cerr := configsEqual(stripDNS(existing), stripDNS(candidate))
			if cerr != nil {
				return result, cerr
			}
			if otherwiseMigrated {
				distributed, distRefusal, distErr := distributeTopLevelDNS(candidate, destDir)
				if distErr != nil {
					result.DNSDistributionRefusal = distRefusal
					return result, distErr
				}
				if distributed {
					result.DNSDistributed = true
					if !write {
						result.WouldWrite = true
						return result, nil
					}
					// The config lock is held (acquired
					// above): write under it, without
					// re-locking via SaveSingleConfig.
					if _, err := writeSingleConfigLocked(destDir, candidate); err != nil {
						return result, err
					}
					result.Migrated = true
					result.Reason = "dns-distributed"
					return result, nil
				}
			}
		}
		// DNS extension: author the interim global section only
		// onto an otherwise already-migrated config (see
		// authorInterimDNS). A differing config refuses below
		// with the candidate unauthored.
		dnsAuthored, dnsRefusal := authorInterimDNS(candidate, existing)
		result.DNSAuthored = dnsAuthored
		result.DNSRefusal = dnsRefusal
		if dnsAuthored {
			if !write {
				result.WouldWrite = true
				return result, nil
			}
			// The config lock is held (acquired above): write
			// under it, without re-locking via SaveSingleConfig.
			if _, err := writeSingleConfigLocked(destDir, candidate); err != nil {
				return result, err
			}
			result.Migrated = true
			result.Reason = "dns-authored"
			return result, nil
		}
		equal, cerr := configsEqual(existing, candidate)
		if cerr != nil {
			return result, cerr
		}
		if equal {
			result.Reason = "already-migrated"
			return result, nil
		}
		result.Reason = "refuse-overwrite"
		return result, newRefuseError("existing single config differs from what migrate would write; refusing to overwrite (no --overwrite in this design)")
	}

	// No existing single file: a fresh migration. A
	// profiles-absent destination file carrying single-format
	// sections is refused first (R1 guard): overwriting it
	// would silently delete those sections, and no later
	// step re-reads them. Its profiles are always
	// direct-only (legacy files carry no outbound), so no
	// dns section can be authored; record the refusal and write
	// the migration without one.
	if refusal, gerr := refuseSingleFormatBaseFile(destDir); gerr != nil {
		result.Errors = append(result.Errors, refusal)
		// The node_id generation above ran in memory only and
		// nothing is written on this refusal: never report an
		// id as generated (the RT-2 rule — a reported id must
		// be a persisted id). Dry-run results carry no
		// generated claim, so this scrub is a no-op there.
		result.Generated = nil
		for i := range result.Profiles {
			result.Profiles[i].NodeIDGenerated = false
			kept := result.Profiles[i].Warnings[:0]
			for _, w := range result.Profiles[i].Warnings {
				if w != "node_id generated" {
					kept = append(kept, w)
				}
			}
			result.Profiles[i].Warnings = kept
		}
		return result, gerr
	}
	if _, refusing, ok := singleDNSDetour(candidate); !ok && refusing != "" {
		result.DNSRefusal = fmt.Sprintf("dns section not authored: profile %q has no outbound tag for a dns detour (direct-only); add an outbound and re-run config migrate, or add a dns section by hand (see docs/config.md)", refusing)
	}

	if !write {
		result.WouldWrite = true
		return result, nil
	}
	// The config lock is held (acquired above): write under
	// it, without re-locking via SaveSingleConfig.
	if _, err := writeSingleConfigLocked(destDir, candidate); err != nil {
		return result, err
	}
	result.Migrated = true
	return result, nil
}

// sameDir reports whether two directory paths name the same
// directory, compared by absolute path after resolving symlinks:
// a symlink alias of a directory compares same as the directory
// itself. When either path cannot be resolved (dangling symlink,
// missing directory), its cleaned absolute path is compared
// instead: resolution failure treats the directories as different
// (fail-open to cross-dir logic), never as same, and never a
// crash. No symlink resolution is attempted beyond the two paths
// themselves.
func sameDir(a, b string) bool {
	absA, errA := filepath.Abs(a)
	if errA != nil {
		absA = a
	}
	absB, errB := filepath.Abs(b)
	if errB != nil {
		absB = b
	}
	absA = filepath.Clean(absA)
	absB = filepath.Clean(absB)
	if resolved, err := filepath.EvalSymlinks(absA); err == nil {
		absA = resolved
	}
	if resolved, err := filepath.EvalSymlinks(absB); err == nil {
		absB = resolved
	}
	return absA == absB
}

// readExistingSingle reads baseDir/config.json if present. It returns
// (nil, false, nil, nil) when absent or legacy-flat, (cfg, true, nil,
// nil) for a single file, (nil, true, nil, err) when the single file
// is unparseable, and (nil, false, malformedErr, nil) when the file is
// malformed JSON (reported as the default profile's error so other
// profiles can still be listed). The legacy-flat branch is
// MIGRATE-ONLY: LoadProfile refuses that state instead of returning
// it, and only Migrate distinguishes "no single file" from "legacy
// base file" this way.
func readExistingSingle(baseDir string) (*SingleConfig, bool, error, error) {
	path := filepath.Join(baseDir, "config.json")
	data, err := readRegularFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, false, nil, nil
		}
		return nil, false, nil, newConfigErrorf("read config: %v", err)
	}
	marker, err := HasProfilesMarker(data)
	if err != nil {
		return nil, false, newConfigErrorf("parse legacy config: %v", err), nil
	}
	if !marker {
		return nil, false, nil, nil
	}
	cfg, err := ParseSingleConfig(data, baseDir)
	if err != nil {
		return nil, true, nil, err
	}
	return cfg, true, nil, nil
}

// singleFormatKeys returns the top-level keys in data whose values
// have the single-config shape for that key, in canonical order.
// data must be a JSON object without a "profiles" key; callers
// check the marker first (HasProfilesMarker). Shape, not key
// presence alone, triggers: a legacy file never carries these
// keys in single-config shape, while a hand-written
// single-format file that lost its "profiles" key does. For the
// array sections and the log object the rule is existential:
// a single shaped element, or a single log-block key, proves
// the section is single-format, even alongside unshaped
// elements or keys.
// Unshaped values (a string "dns", an empty outbounds array, an
// array with no shaped outbound, a wireguard_dns map with no
// string in any value array, a log object with no log-block
// key — including an empty log object, which carries no keys
// or values to lose) are left to the legacy path
// exactly as before — the guard refuses only state it can
// prove is single-format, so no legitimate legacy migration is
// affected.
func singleFormatKeys(data []byte) []string {
	obj, err := decodeOrderedObject(data)
	if err != nil {
		return nil
	}
	var keys []string
	if v, ok := obj.get("dns"); ok {
		if _, isObj := v.(*orderedObject); isObj {
			keys = append(keys, "dns")
		}
	}
	for _, key := range []string{"outbounds", "endpoints"} {
		if v, ok := obj.get(key); ok {
			if arr, isArr := v.([]any); isArr && len(arr) > 0 && anyOutboundShaped(arr) {
				keys = append(keys, key)
			}
		}
	}
	if v, ok := obj.get("wireguard_dns"); ok {
		if m, isObj := v.(*orderedObject); isObj && len(m.keys) > 0 && anyStringArray(m) {
			keys = append(keys, "wireguard_dns")
		}
	}
	if v, ok := obj.get("log"); ok {
		if m, isObj := v.(*orderedObject); isObj && len(m.keys) > 0 && anyLogKey(m) {
			keys = append(keys, "log")
		}
	}
	if v, ok := obj.get("default_profile"); ok {
		if _, isStr := v.(string); isStr {
			keys = append(keys, "default_profile")
		}
	}
	return keys
}

// anyOutboundShaped reports whether any element is an object
// carrying a non-empty string "type": the outbound/endpoint
// object shape. A single shaped element proves the array
// carries single-format state, even alongside unshaped
// elements; an object without a type is not shaped state.
func anyOutboundShaped(arr []any) bool {
	for _, elem := range arr {
		obj, ok := elem.(*orderedObject)
		if !ok {
			continue
		}
		t, ok := obj.get("type")
		if !ok {
			continue
		}
		s, ok := t.(string)
		if ok && s != "" {
			return true
		}
	}
	return false
}

// anyStringArray reports whether any value in m is an array
// containing at least one string: the wireguard_dns map shape.
// A single string in any value array proves the map carries
// single-format state, even alongside unshaped values.
func anyStringArray(m *orderedObject) bool {
	for _, k := range m.keys {
		arr, ok := m.values[k].([]any)
		if !ok {
			continue
		}
		for _, elem := range arr {
			if _, ok := elem.(string); ok {
				return true
			}
		}
	}
	return false
}

// anyLogKey reports whether any key in m is one of the four
// log-block keys: the log section shape (see internal/profile/log.go).
// A single log-block key proves the object carries single-format
// state, even alongside unknown keys; an object with no
// log-block key carries none.
func anyLogKey(m *orderedObject) bool {
	for _, k := range m.keys {
		switch k {
		case "disabled", "level", "output", "timestamp":
			return true
		}
	}
	return false
}

// refuseSingleFormatBaseFile refuses a fresh migration when the
// destination config.json is a profiles-absent file carrying
// single-format sections (R1): a fresh migration would
// overwrite it with a synthetic profile set, silently deleting
// those sections — the exact loss the red-team fixture
// proved, directed by the legacy-layout error text. It returns
// ("", nil) when the file is absent, unparseable (the existing
// malformed path handles that), carries a "profiles" key (the
// single path handles that), or carries no shaped
// single-format section (a genuine legacy file, which keeps
// migrating). The refusal names keys/fields only, never values.
func refuseSingleFormatBaseFile(destDir string) (string, error) {
	path := filepath.Join(destDir, "config.json")
	data, err := readRegularFile(path)
	if err != nil {
		return "", nil
	}
	marker, err := HasProfilesMarker(data)
	if err != nil || marker {
		return "", nil
	}
	keys := singleFormatKeys(data)
	if len(keys) == 0 {
		return "", nil
	}
	quoted := make([]string, len(keys))
	for i, k := range keys {
		quoted[i] = fmt.Sprintf("%q", k)
	}
	refusal := fmt.Sprintf("migrate: destination config file %q carries single-format section(s) %s but no \"profiles\" key; refusing to overwrite it with a fresh migration (add a \"profiles\" object so the file parses as a single config, or remove the sections by hand first, see docs/config.md)", path, strings.Join(quoted, ", "))
	return refusal, newConfigError(refusal)
}

