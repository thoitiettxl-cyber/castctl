// migrateLegacyProfile loads one legacy profile strictly: wrong-typed
// settings are errors, not silent coercions. A missing config file
// yields defaults. It never writes. MIGRATE-ONLY: this is the sole
// reader of legacy files (through parseLegacyConfig strict mode and
// applyLegacy); LoadProfile refuses legacy files instead.
func migrateLegacyProfile(baseDir, name string, paths Paths) (*Profile, error) {
	data, err := readRegularFile(paths.Config)
	if err != nil {
		if os.IsNotExist(err) {
			p := defaultProfile(paths)
			p.Name = name
			return p, nil
		}
		return nil, newConfigErrorf("profile %q: read config: %v", name, err)
	}
	s, err := parseLegacyConfig(data, true)
	if err != nil {
		return nil, err
	}
	return applyLegacy(name, paths, s, baseDir), nil
}

// legacyProfileSettingsEqual compares the settings a legacy file
// carries (cookies_file, vm_id, node_id, auto_approve,
// auto_allow_once, subscription_action_id, fingerprint,
// tls_engine) between a profile built from a legacy file and a
// single-file entry. The outbound is excluded: a legacy file never
// carries one, and a destination entry's outbound is preserved
// verbatim either way. Cookies files compare equal when literally
// equal, or when both are the profile's own default cookies path
// (the same "no cookies_file key" state in different directories).
func legacyProfileSettingsEqual(a, b *Profile) bool {
	if a == nil || b == nil {
		return a == b
	}
	// Cookies files compare equal when literally equal, or when
	// both are the profile's own default cookies path (the same
	// "no cookies_file key" state in different directories).
	cookiesEqual := a.CookiesFile == b.CookiesFile ||
		(a.CookiesFile == filepath.Join(a.Dir, "cookies.txt") &&
			b.CookiesFile == filepath.Join(b.Dir, "cookies.txt"))
	return cookiesEqual &&
		a.VMID == b.VMID &&
		a.NodeID == b.NodeID &&
		a.AutoApprove == b.AutoApprove &&
		a.AutoAllowOnce == b.AutoAllowOnce &&
		a.SubscriptionActionID == b.SubscriptionActionID &&
		a.Fingerprint == b.Fingerprint &&
		a.TLSEngine == b.TLSEngine
}

func migrateWarnings(p *Profile, write bool, generatedSet map[string]bool) []string {
	warnings := []string{}
	if _, err := os.Stat(p.CookiesFile); err != nil {
		warnings = append(warnings, "missing cookies file")
	}
	if generatedSet[p.Name] {
		warnings = append(warnings, "node_id generated")
	} else if !p.nodeIDPresent || p.NodeID == "" {
		if !write {
			warnings = append(warnings, "node_id will be generated on --write")
		}
	}
	return warnings
}

// generateNodeID returns 16 lowercase hex chars from crypto/rand
// (secrets.token_hex(8) equivalent).
func generateNodeID() (string, error) {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", newConfigErrorf("generate node_id: %v", err)
	}
	return hex.EncodeToString(b[:]), nil
}

// configsEqual compares two SingleConfigs by their canonical saved
// encoding (parsed-equal, ignoring file formatting).
func configsEqual(a, b *SingleConfig) (bool, error) {
	ab, err := canonicalSingleBytes(a)
	if err != nil {
		return false, err
	}
	bb, err := canonicalSingleBytes(b)
	if err != nil {
		return false, err
	}
	return string(ab) == string(bb), nil
}

func canonicalSingleBytes(cfg *SingleConfig) ([]byte, error) {
	if cfg.Profiles == nil {
		cfg.Profiles = make(map[string]*Profile)
	}
	root, err := buildSingleFileOrdered(cfg)
	if err != nil {
		return nil, err
	}
	return encodeOrderedJSONIndent(root, 2)
}

// interimDNSServerTag is the tag of the single server in the interim
// global dns section authored by authorInterimDNS.
const interimDNSServerTag = "castctl-doh"

// singleDNSDetour returns the one detour tag every profile in cfg
// routes through. A profile's detour tag is its outbound tag
// reference, its endpoint tag reference, or its inline outbound's
// tag — except when detourTagForProfile finds no usable detour
// chain for it (direct-only, or a chain terminating in an empty
// direct outbound, an empty group, a urltest, a block, or a
// bridge), which carries no detour tag at all. The runtime "direct" outbound is synthesised at runtime
// (createOutbounds) and the synthetic "castctl-dialer" exists only
// for direct endpoint references; neither is a config tag, so
// neither can be a detour here (validateTagGraph would reject
// them as dangling, and sing-box rejects a detour to an empty
// direct outbound). When no single detour exists, the second
// return names the first profile in sorted order that has no
// detour tag or a different one, and ok is false. With no profiles
// at all there is nothing to route for: ("", "", false).
func singleDNSDetour(cfg *SingleConfig) (detour, refusing string, ok bool) {
	if cfg == nil || len(cfg.Profiles) == 0 {
		return "", "", false
	}
	for _, name := range cfg.ProfileNames() {
		p := cfg.Profiles[name]
		tag := detourTagForProfile(cfg, p)
		if detour == "" {
			if tag == "" {
				return "", name, false
			}
			detour = tag
			continue
		}
		if tag != detour {
			return "", name, false
		}
	}
	return detour, "", true
}

// detourNode is one outbound/endpoint/inline node in the tag graph,
// resolved by tag for detour-chain walking.
type detourNode struct {
	tag     string
	typ     string
	options any
}

// lookupDetourNode resolves tag to its node: an outbound, an
// endpoint, or another profile's inline outbound. A tag that
// resolves to nothing is not found; the caller decides whether
// that is a dangling reference (left for validateTagGraph) or an
// unusable path.
func lookupDetourNode(cfg *SingleConfig, tag string) (detourNode, bool) {
	if cfg == nil {
		return detourNode{}, false
	}
	for _, ob := range cfg.Outbounds {
		if ob.Tag == tag {
			return detourNode{tag: tag, typ: ob.Type, options: ob.Options}, true
		}
	}
	for _, ep := range cfg.Endpoints {
		if ep.Tag == tag {
			return detourNode{tag: tag, typ: ep.Type, options: ep.Options}, true
		}
	}
	for _, p := range cfg.Profiles {
		if p.Outbound.Kind == OutboundInline && p.Outbound.Tag == tag {
			ob, err := p.Outbound.InlineOutbound()
			if err != nil || ob == nil {
				return detourNode{}, false
			}
			return detourNode{tag: tag, typ: ob.Type, options: ob.Options}, true
		}
	}
	return detourNode{}, false
}

// selectorSelected returns the one member upstream dials for a
// selector: its Default when set, else its first member
// (sing-box v1.14.4 protocol/group/selector.go: selector Start
// prefers a cache-file selection, then Default, then the first
// member, and DialContext dials only the selected member). Castctl
// registers no CacheFile service (internal/outbound/context.go
// services()), so in castctl runtime the selection is exactly
// Default-or-first. A Default naming a non-member, or an empty
// member list, selects nothing: upstream Start errors in both
// cases ("default outbound not found", "missing tags"), so the
// selector is unusable here.
func selectorSelected(options any) (string, bool) {
	opts, ok := options.(*option.SelectorOutboundOptions)
	if !ok || len(opts.Outbounds) == 0 {
		return "", false
	}
	if opts.Default != "" {
		for _, m := range opts.Outbounds {
			if m == opts.Default {
				return m, true
			}
		}
		return "", false
	}
	return opts.Outbounds[0], true
}

// detourNodeCanDial reports whether dialing through node can ever
// succeed, walking detour fields and selector selected members
// recursively (visiting guards detour cycles: a cycle can never
// dial, so it is unusable). asDetourTarget distinguishes the two
// ways a node is reached: as a DETOUR target (DetourDialer.init
// refuses an empty direct outbound) or as a node dialed through
// directly (a selector dials its selected member directly, with
// no empty-direct check — so a direct member dials fine even
// though it cannot itself serve as a detour target). The per-type
// answers below match sing-box v1.14.4 upstream (see
// docs/provenance.md §1, outbound-dialability mapping); the two
// castctl-runtime deviations are urltest (unstartable here, see
// its case) and direct-with-detour (rejected at construction
// upstream, so a walker answer for it is moot — the walk still
// follows the detour field, and the config fails at runtime
// construction regardless of dns authoring).
func detourNodeCanDial(cfg *SingleConfig, node detourNode, visiting map[string]bool, asDetourTarget bool) bool {
	if node.tag != "" {
		if visiting[node.tag] {
			return false
		}
		visiting[node.tag] = true
		defer delete(visiting, node.tag)
	}
	// A detour field takes precedence: dialing goes through the
	// detour target first, and the detour target is always
	// reached as a detour target (its own DetourDialer.init runs).
	if d := detourOf(node.options); d != "" {
		target, ok := lookupDetourNode(cfg, d)
		if !ok {
			return false
		}
		return detourNodeCanDial(cfg, target, visiting, true)
	}
	switch node.typ {
	case "direct":
		// As a detour target, empty means zero DialerOptions (sing-box
		// protocol/direct IsEmpty: DeepEqual against the zero
		// value) and the detour is refused. Dialed through
		// directly, a direct outbound always dials; a direct
		// outbound carrying any dialer option (a bind address,
		// a routing mark, …) is non-empty and serves as a detour
		// target too. The castctl comparison below is exactly
		// upstream's: upstream forces UDPFragmentDefault true
		// before comparing (protocol/direct/outbound.go
		// NewOutbound + IsEmpty), and that field is json:"-"
		// (option/outbound.go), so a parsed config can never set
		// it — parsed-zero is exactly upstream-empty.
		if asDetourTarget {
			if w, ok := node.options.(option.DialerOptionsWrapper); ok {
				return !reflect.DeepEqual(w.TakeDialerOptions(), option.DialerOptions{})
			}
			return false
		}
		return true
	case "selector":
		// Upstream DialContext dials ONLY the selected member
		// (protocol/group/selector.go DialContext + Start), so
		// the walk follows that one member — never "any member
		// dials". The selected member is dialed directly, not as
		// a detour target.
		selected, ok := selectorSelected(node.options)
		if !ok {
			return false
		}
		target, ok := lookupDetourNode(cfg, selected)
		if !ok {
			return false
		}
		return detourNodeCanDial(cfg, target, visiting, false)
	case "urltest":
		// Unusable in castctl runtime regardless of members:
		// upstream urltest Start requires a URL test history
		// storage service (protocol/group/urltest.go
		// NewURLTestGroup: nil history is "missing URL test
		// history storage"), upstream box registers one (box.go),
		// but castctl's manager context never does
		// (internal/outbound/context.go services()), so a urltest
		// outbound cannot start here at all. This refuses every
		// detour whose dial target IS a urltest. (In sing-box
		// proper, urltest would dial its best-tested member; the
		// castctl deviation is recorded in docs/provenance.md.)
		return false
	case "block", "bridge":
		// Never dial, upstream: block DialContext always returns
		// EPERM (protocol/block/outbound.go DialContext), and
		// bridge DialContext always errors ("only L3 traffic is
		// supported by bridge", protocol/bridge/outbound.go
		// DialContext). A dns detour through either can never
		// carry a query. (A dns outbound needs no case: sing-box
		// 1.14.4 rejects it at parse time, option/outbound.go,
		// so the walker never sees one.)
		return false
	default:
		// Any other outbound/endpoint type dials through its
		// own transport. Endpoint (e.g. WireGuard) dial validity
		// is [UNVERIFIED]: the tag is kept, not claimed proven.
		return true
	}
}

// detourTagForProfile returns the tag a dns detour for p would name,
// or "" when p is direct-only or every detour chain from p
// terminates unusably (empty direct, empty group, dangling tag,
// urltest, block, or bridge) — authoring a detour to such a target
// writes a config sing-box refuses at runtime, so no dns section
// may be authored for it. Detour chains are walked through detour
// fields and selector selected members with a cycle guard; a tag
// that resolves to nothing is returned as-is and left for
// validateTagGraph to reject as dangling.
func detourTagForProfile(cfg *SingleConfig, p *Profile) string {
	if p == nil {
		return ""
	}
	switch p.Outbound.Kind {
	case OutboundTag:
		node, ok := lookupDetourNode(cfg, p.Outbound.Tag)
		if !ok {
			return p.Outbound.Tag
		}
		if detourNodeCanDial(cfg, node, map[string]bool{}, true) {
			return p.Outbound.Tag
		}
		return ""
	case OutboundInline:
		ob, err := p.Outbound.InlineOutbound()
		if err != nil || ob == nil {
			return p.Outbound.Tag
		}
		node := detourNode{tag: p.Outbound.Tag, typ: ob.Type, options: ob.Options}
		if detourNodeCanDial(cfg, node, map[string]bool{}, true) {
			return p.Outbound.Tag
		}
		return ""
	default:
		return ""
	}
}

// authorInterimDNS authors the INTERIM global dns section onto
// candidate when the candidate has no dns section, the existing
// single file (when one exists) is otherwise identical to the
// candidate, and a single detour serves every profile. The authored
// section is the gated default only: one DoH server (https,
// IP-literal 1.1.1.1, no bootstrap hostname, path /dns-query)
// through the shared detour. It is global and single-profile-only
// by construction: the final model is a per-profile dns block,
// and this section is distributed into profile entries by
// `config migrate` (G4: distributeTopLevelDNS). Authoring is validated with
// the same checks a hand-written section faces (validateTagGraph
// plus the WireGuard key-sharing check); a validation failure
// falls back to no section with the refusal recorded, never to a
// written-but-invalid config. When candidate already carries a
// dns section, or differs from the existing file beyond dns, or
// no single detour exists, nothing is authored: the refusal is
// returned ("" when authoring was not applicable because a
// section already exists or the config differs).
func authorInterimDNS(candidate, existing *SingleConfig) (authored bool, refusal string) {
	if candidate == nil || candidate.DNS != nil || len(candidate.rawDNS) > 0 {
		return false, ""
	}
	// Per-profile DNS (G1 coexistence): authoring a global
	// section onto a config where any profile already carries
	// its own dns block would produce a file the loader
	// rejects, so refuse instead of writing it.
	for _, name := range candidate.ProfileNames() {
		if p := candidate.Profiles[name]; p != nil && p.dnsPresent {
			return false, fmt.Sprintf("dns section not authored: profile %q already has a per-profile dns block; a top-level dns section would conflict (see docs/config.md)", name)
		}
	}
	if existing != nil {
		equal, err := configsEqual(stripDNS(existing), stripDNS(candidate))
		if err != nil || !equal {
			return false, ""
		}
	}
	detour, refusing, ok := singleDNSDetour(candidate)
	if !ok {
		if refusing == "" {
			return false, ""
		}
		return false, fmt.Sprintf("dns section not authored: profile %q does not share one detour tag with every other profile (direct-only, or a different outbound tag); add a shared outbound and re-run config migrate, or add a dns section by hand (see docs/config.md)", refusing)
	}
	detourJSON, err := json.Marshal(detour)
	if err != nil {
		return false, fmt.Sprintf("dns section not authored: cannot encode detour tag: %v", err)
	}
	raw := []byte(fmt.Sprintf(`{"servers":[{"tag":%q,"type":"https","server":"1.1.1.1","server_port":443,"path":"/dns-query","detour":%s}],"final":%q}`,
		interimDNSServerTag, detourJSON, interimDNSServerTag))
	dnsOpts, err := parseDNS(raw)
	if err != nil {
		return false, fmt.Sprintf("dns section not authored: %v", err)
	}
	candidate.DNS = dnsOpts
	candidate.rawDNS = raw
	if err := validateTagGraph(candidate); err != nil {
		candidate.DNS = nil
		candidate.rawDNS = nil
		return false, fmt.Sprintf("dns section not authored: %v", err)
	}
	if err := validateWireGuardPrivateKeys(candidate); err != nil {
		candidate.DNS = nil
		candidate.rawDNS = nil
		return false, fmt.Sprintf("dns section not authored: %v", err)
	}
	return true, ""
}

// stripDNS returns a shallow copy of cfg with no dns section, so
// configsEqual can compare two configs ignoring dns.
func stripDNS(cfg *SingleConfig) *SingleConfig {
	if cfg == nil {
		return nil
	}
	cp := *cfg
	cp.DNS = nil
	cp.rawDNS = nil
	return &cp
}

// cloned, outbound/endpoint lists and raw JSON slices are copied, so
// mutating the clone never affects the original.
func cloneSingleConfig(cfg *SingleConfig) *SingleConfig {
	if cfg == nil {
		return nil
	}
	out := *cfg
	out.Profiles = make(map[string]*Profile, len(cfg.Profiles))
	for name, p := range cfg.Profiles {
		out.Profiles[name] = p.clone()
	}
	out.Outbounds = slices.Clone(cfg.Outbounds)
	out.Endpoints = slices.Clone(cfg.Endpoints)
	out.rawOutbounds = copyRawList(cfg.rawOutbounds)
	out.rawEndpoints = copyRawList(cfg.rawEndpoints)
	if len(cfg.rawDNS) > 0 {
		out.rawDNS = append([]byte{}, cfg.rawDNS...)
	} else {
		out.rawDNS = nil
	}
	if len(cfg.rawWireGuardDNS) > 0 {
		out.rawWireGuardDNS = append([]byte{}, cfg.rawWireGuardDNS...)
	} else {
		out.rawWireGuardDNS = nil
	}
	if len(cfg.rawLog) > 0 {
		out.rawLog = append([]byte{}, cfg.rawLog...)
	} else {
		out.rawLog = nil
	}
	if len(cfg.rawTelegram) > 0 {
		out.rawTelegram = append([]byte{}, cfg.rawTelegram...)
	} else {
		out.rawTelegram = nil
	}
	if cfg.Log != nil {
		logCopy := *cfg.Log
		out.Log = &logCopy
	}
	if cfg.Telegram != nil {
		tgCopy := *cfg.Telegram
		tgCopy.AllowedUserIDs = append([]int64{}, cfg.Telegram.AllowedUserIDs...)
		out.Telegram = &tgCopy
	}
	if len(cfg.WireGuardDNS) > 0 {
		out.WireGuardDNS = make(map[string][]string, len(cfg.WireGuardDNS))
		for tag, servers := range cfg.WireGuardDNS {
			out.WireGuardDNS[tag] = append([]string{}, servers...)
		}
	} else {
		out.WireGuardDNS = nil
	}
	out.rawProfiles = make(map[string][]byte, len(cfg.rawProfiles))
	for name, raw := range cfg.rawProfiles {
		out.rawProfiles[name] = append([]byte{}, raw...)
	}
	if cfg.DNS != nil {
		dnsCopy := *cfg.DNS
		out.DNS = &dnsCopy
	}
	return &out
}

// singleFirstNames returns names with "default" first and the rest in
// their given (sorted) order, matching DiscoverProfileNames order.
func singleFirstNames(names []string) []string {
	out := make([]string, 0, len(names))
	for _, n := range names {
		if n == DefaultProfileName {
			out = append(out, n)
		}
	}
	for _, n := range names {
		if n != DefaultProfileName {
			out = append(out, n)
		}
	}
	return out
}
