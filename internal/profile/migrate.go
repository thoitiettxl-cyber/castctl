// MigrateProfile is one profile in a MigrateResult.
type MigrateProfile struct {
	Name string `json:"name"`
	// Source is "legacy" for profiles built from the old layout and
	// "single" for profiles carried over verbatim from an existing
	// single file (NB4: single-file-only profiles).
	Source string `json:"source"`
	// CookiesFile is the resolved cookies file path.
	CookiesFile string `json:"cookies_file"`
	// Outbound is always nil (null) for migrated profiles: migration
	// never invents an outbound.
	Outbound *OutboundRef `json:"outbound"`
	// Warnings lists non-fatal observations, e.g. a missing cookies
	// file or a generated node_id. Warning text never contains secret
	// values.
	Warnings []string `json:"warnings"`
	// NodeIDGenerated reports that a node_id was generated for this
	// profile (write mode only; dry-run never invents one).
	NodeIDGenerated bool `json:"node_id_generated,omitempty"`
}

// MigrateResult is the JSON-marshalable result of Migrate. The caller
// decides the exit code from the returned error: any profile error or
// a refuse-overwrite produces a non-nil error, but the result still
// lists the good profiles that would migrate.
type MigrateResult struct {
	// SourceDir is the directory legacy profiles were read from.
	SourceDir string `json:"source_dir"`
	// DestinationDir is the directory the single config was (or
	// would be) written to.
	DestinationDir string `json:"destination_dir"`
	// WouldWrite reports whether a dry-run would write a file. False
	// after migration (already-migrated) and when overwriting is refused.
	WouldWrite bool `json:"would_write"`
	// Migrated reports whether this call wrote the single file.
	Migrated bool `json:"migrated"`
	// Reason is "already-migrated", "refuse-overwrite", or
	// "dns-authored" (a run that wrote only the interim dns section
	// onto an otherwise already-migrated config) when applicable.
	Reason               string           `json:"reason,omitempty"`
	DefaultProfile       string           `json:"default_profile"`
	Profiles             []MigrateProfile `json:"profiles"`
	ExistingSingleConfig bool             `json:"existing_single_config"`
	// Errors lists per-profile error messages (no secret values).
	Errors []string `json:"errors"`
	// Generated lists profile names whose node_id was generated by
	// this write. Never populated by a dry-run.
	Generated []string `json:"generated,omitempty"`
	// DNSAuthored reports that this run authored the interim global
	// dns section (see authorInterimDNS). It is set only when the
	// candidate had no dns section and every profile shared one
	// outbound tag to detour through.
	DNSAuthored bool `json:"dns_authored,omitempty"`
	// DNSRefusal records why no dns section was authored, naming
	// the profile that has no single detour (or the validation
	// failure). It is informational: the migration itself still
	// succeeds and writes no dns section. Empty when a dns section
	// was carried verbatim, authored, or not applicable.
	DNSRefusal string `json:"dns_refusal,omitempty"`
}

// Migrate migrates the legacy layout in baseDir into baseDir's
// single config. It is MigrateFrom with source == destination.
func Migrate(baseDir string, write bool) (*MigrateResult, error) {
	return MigrateFrom(baseDir, baseDir, write)
}

// MigrateFrom implements `config migrate` as a library function.
// With write=false it is a dry-run: it prints
// nothing and writes no files. With write=true it writes the single
// file atomically (0600) and never deletes or modifies any old file.
//
//   - A second run over identical parsed content returns
//     {migrated:false, reason:"already-migrated"} with no error.
//     Profiles present only in the single file (no legacy layout),
//     and the file's outbounds/endpoints/dns/default_profile, are
//     carried over verbatim (NB4), so a single-file-only layout is
//     already-migrated on the first run too; comparison happens
//     before any node_id generation.
//   - A different existing single file is a refuse-overwrite error:
//     migrate is one-shot and has no --overwrite; later profiles are
//     added via profile-add, not migrate.
//   - Fingerprint and tls_engine values present in a profile entry
//     or legacy file are preserved verbatim; absent keys stay at
//     their defaults (and stay absent in the written file).
//   - A missing node_id is generated with crypto/rand (16 hex chars)
//     only in write mode, listed in Generated, and never written back
//     to old files.
//   - Any profile error is an overall error, but the result still
//     lists the good profiles; in write mode nothing is written when
//     any profile error exists (all-or-nothing).
//   - DNS extension (interim global section only): when the
//     candidate has no dns section, authorInterimDNS authors the
//     gated default DoH section only if every profile shares one
//     outbound tag to detour through, and only onto a config that
//     is otherwise already-migrated. Otherwise it records the
//     refusal (DNSRefusal, naming the profile) and writes no dns
//     section; the migration itself still succeeds. A fresh
//     legacy migration is always direct-only, so it always
//     records a refusal: there is no outbound tag to detour
//     through until an outbound is supplied separately.
//   - Migrate reads files only: it does not consult MUSE_VM_ID /
//     MUSE_NODE_ID (env fill happens at Load time), and touches no
//     telegram or update files.
//
// MigrateFrom migrates legacy profiles from sourceDir into the single
// config in destDir (`config migrate --from`). The source directory
// is read-only: it is never written, locked, or modified in any way,
// and legacy files there keep serving as the backup. The destination
// holds the config lock in write mode, the refuse-overwrite decision,
// and the atomic 0600 write. When sourceDir == destDir (compared by
// cleaned absolute path) behaviour is exactly Migrate's. When they
// differ, the source directory must exist and be a directory, else
// the run is an exit-2 error that writes nothing; a single-format
// file in the source is not copied — the strict legacy parser
// refuses it as a profile error, like any other non-legacy source
// content. Cookies files stay where they are: migrated entries point
// at the source cookies files by absolute path.
func MigrateFrom(sourceDir, destDir string, write bool) (*MigrateResult, error) {
	result := &MigrateResult{
		SourceDir:      sourceDir,
		DestinationDir: destDir,
		Profiles:       []MigrateProfile{},
		Errors:         []string{},
	}
	if destDir == "" {
		return result, newConfigError("migrate: destination directory must not be empty")
	}
	if sourceDir == "" {
		sourceDir = destDir
		result.SourceDir = destDir
	}
	same := sameDir(sourceDir, destDir)
	if !same {
		info, serr := os.Stat(sourceDir)
		if serr != nil {
			if os.IsNotExist(serr) {
				return result, newConfigErrorf("migrate: source directory %q does not exist", sourceDir)
			}
			return result, newConfigErrorf("migrate: cannot stat source directory %q: %v", sourceDir, serr)
		}
		if !info.IsDir() {
			return result, newConfigErrorf("migrate: source %q is not a directory", sourceDir)
		}
	}

	// Write mode holds the config lock across the WHOLE
	// decide+write (RT-2): the already-migrated/refuse
	// decision, the node_id generation, and the write all
	// happen under one lock acquisition, re-reading the
	// current single file under the lock. Without this, two
	// concurrent `migrate --write` runs both decided on the
	// absent file, both generated different node_ids, and
	// both exited 0 with the last write winning — the other
	// run reported ids that were never persisted — and a
	// concurrent `profile add` could be clobbered by the
	// stale-candidate write. Under the lock the second
	// migrate re-reads the file the first one wrote and
	// reports already-migrated, and an add serialises either
	// before (carried over verbatim, NB4) or after the
	// migrate. The write below therefore uses
	// writeSingleConfigLocked directly: SaveSingleConfig
	// would re-acquire the lock and deadlock. Migrate must
	// not be called from inside an UpdateSingleConfig update
	// function (the lock is already held there). Dry-run
	// takes no lock: it reads only. The lock is always the
	// DESTINATION's: the source is read-only and needs none.
	if write {
		release, err := lockConfigDir(destDir)
		if err != nil {
			return result, err
		}
		defer release()
	}

	existing, existingIsSingle, malformedErr, err := readExistingSingle(destDir)
	if err != nil {
		return result, err
	}
	if malformedErr != nil && !same {
		// A malformed destination file is not a legacy source
		// profile error: refuse to overwrite it blindly.
		return result, malformedErr
	}
	result.ExistingSingleConfig = existingIsSingle

	// Discover legacy profiles: default first, then sorted dir names.
	names, err := DiscoverProfileNames(sourceDir)
	if err != nil {
		return result, err
	}
	sort.Strings(names[1:])

	// NB4: when a single file already exists it wins wholly. Its
	// entries are carried over verbatim (cloned) first, including
	// profiles present ONLY in the single file: DiscoverProfileNames
	// only sees directories, so single-only names never appear in
	// `names` and were previously dropped, making every second run
	// refuse-overwrite. Legacy files are then consulted ONLY for
	// profiles absent from the single file.
	candidateProfiles := []*Profile{}
	fromSingle := make(map[string]bool)
	if existingIsSingle {
		for _, name := range singleFirstNames(existing.ProfileNames()) {
			candidateProfiles = append(candidateProfiles, existing.Profiles[name].clone())
			fromSingle[name] = true
		}
	}
	profileErrors := []string{}
	for _, name := range names {
		paths, perr := ProfilePaths(sourceDir, name)
		if perr != nil {
			profileErrors = append(profileErrors, perr.Error())
			continue
		}
		if malformedErr != nil && same && name == DefaultProfileName {
			// The base config.json is malformed JSON: record it once
			// as the default profile's error; do not re-read it as a
			// legacy file. (Only when source == destination: the
			// malformed file IS the source base file. A malformed
			// destination file with a separate source is refused
			// above, before discovery.)
			profileErrors = append(profileErrors, malformedErr.Error())
			continue
		}
		if existingIsSingle {
			if fromSingle[name] {
				continue
			}
			if name == DefaultProfileName && same {
				// The base config.json IS the single file; the
				// default profile has no separate legacy file,
				// and it is absent from the single file, so
				// there is no default entry to carry over.
				// With a separate source dir, the source base
				// file IS a separate legacy file and migrates
				// like any named profile (no skip).
				continue
			}
		}
		p, perr := migrateLegacyProfile(sourceDir, name, paths)
		if perr != nil {
			profileErrors = append(profileErrors, perr.Error())
			continue
		}
		candidateProfiles = append(candidateProfiles, p)
	}

	// Generate missing node_ids only in write mode and only when
	// there is no existing single file: an already-migrated file is
	// compared verbatim (NB4) before any generation, so a second run
	// never invents an id for a profile already in the single file,
	// and a refused run never reports ids it did not write.
	generated := []string{}
	if write && !existingIsSingle {
		for _, p := range candidateProfiles {
			if !p.nodeIDPresent || p.NodeID == "" {
				id, gerr := generateNodeID()
				if gerr != nil {
					return result, gerr
				}
				p.NodeID = id
				p.nodeIDPresent = true
				generated = append(generated, p.Name)
			}
		}
	}

	// The effective default_profile reported in the result; the
	// candidate file itself reuses the existing value verbatim (even
	// when absent) so comparison against an existing file is exact.
	effectiveDefault := DefaultProfileName
	if existingIsSingle && existing.DefaultProfile != "" {
		effectiveDefault = existing.DefaultProfile
	}
	result.DefaultProfile = effectiveDefault
	generatedSet := make(map[string]bool, len(generated))
	for _, g := range generated {
		generatedSet[g] = true
	}
	for _, p := range candidateProfiles {
		source := "legacy"
		if fromSingle[p.Name] {
			source = "single"
		}
		mp := MigrateProfile{
			Name:            p.Name,
			Source:          source,
			CookiesFile:     p.CookiesFile,
			Outbound:        nil,
			Warnings:        migrateWarnings(p, write, generatedSet),
			NodeIDGenerated: generatedSet[p.Name],
		}
		if mp.Warnings == nil {
			mp.Warnings = []string{}
		}
		result.Profiles = append(result.Profiles, mp)
	}
	result.Generated = generated
	if len(profileErrors) > 0 {
		result.Errors = append(result.Errors, profileErrors...)
		return result, newConfigErrorf("migrate: %d profile error(s)", len(profileErrors))
	}

	var candidate *SingleConfig
	if existingIsSingle {
		// Carry the existing file's outbounds, endpoints, dns, and
		// default_profile verbatim (NB4); only legacy-only profiles
		// are added.
		candidate = cloneSingleConfig(existing)
		for _, p := range candidateProfiles {
			if !fromSingle[p.Name] {
				candidate.Profiles[p.Name] = p
			}
		}
	} else {
		candidate = &SingleConfig{
			DefaultProfile: DefaultProfileName,
			Profiles:       make(map[string]*Profile),
		}
		for _, p := range candidateProfiles {
			candidate.Profiles[p.Name] = p
		}
	}

	if existingIsSingle {
		// DNS extension: author the interim global section only
		// onto an otherwise already-migrated config (see
		// authorInterimDNS). A differing config refuses below
		// with the candidate unauthored.
		dnsAuthored, dnsRefusal := authorInterimDNS(candidate, existing)
		result.DNSAuthored = dnsAuthored
		result.DNSRefusal = dnsRefusal
		if dnsAuthored {
			if !write {
				result.WouldWrite = true
				return result, nil
			}
			// The config lock is held (acquired above): write
			// under it, without re-locking via SaveSingleConfig.
			if _, err := writeSingleConfigLocked(destDir, candidate); err != nil {
				return result, err
			}
			result.Migrated = true
			result.Reason = "dns-authored"
			return result, nil
		}
		equal, cerr := configsEqual(existing, candidate)
		if cerr != nil {
			return result, cerr
		}
		if equal {
			result.Reason = "already-migrated"
			return result, nil
		}
		result.Reason = "refuse-overwrite"
		return result, newRefuseError("existing single config differs from what migrate would write; refusing to overwrite (no --overwrite in this design)")
	}

	// No existing single file: a fresh migration. Its profiles are
	// always direct-only (legacy files carry no outbound), so no
	// dns section can be authored; record the refusal and write
	// the migration without one.
	if _, refusing, ok := singleDNSDetour(candidate); !ok && refusing != "" {
		result.DNSRefusal = fmt.Sprintf("dns section not authored: profile %q has no outbound tag for a dns detour (direct-only); add an outbound and re-run config migrate, or add a dns section by hand (see docs/config.md)", refusing)
	}

	if !write {
		result.WouldWrite = true
		return result, nil
	}
	// The config lock is held (acquired above): write under
	// it, without re-locking via SaveSingleConfig.
	if _, err := writeSingleConfigLocked(destDir, candidate); err != nil {
		return result, err
	}
	result.Migrated = true
	return result, nil
}

// sameDir reports whether two directory paths name the same directory,
// compared by cleaned absolute path. Symlinked aliases of one
// directory compare unequal; that is safe (the source is read-only
// and the destination write lands in the same physical directory
// either way), and no symlink resolution is attempted on a
// destination that may not exist yet.
func sameDir(a, b string) bool {
	absA, errA := filepath.Abs(a)
	absB, errB := filepath.Abs(b)
	if errA != nil || errB != nil {
		return filepath.Clean(a) == filepath.Clean(b)
	}
	return filepath.Clean(absA) == filepath.Clean(absB)
}

// readExistingSingle reads baseDir/config.json if present. It returns
// (nil, false, nil, nil) when absent or legacy-flat, (cfg, true, nil,
// nil) for a single file, (nil, true, nil, err) when the single file
// is unparseable, and (nil, false, malformedErr, nil) when the file is
// malformed JSON (reported as the default profile's error so other
// profiles can still be listed). The legacy-flat branch is
// MIGRATE-ONLY: LoadProfile refuses that state instead of returning
// it, and only Migrate distinguishes "no single file" from "legacy
// base file" this way.
func readExistingSingle(baseDir string) (*SingleConfig, bool, error, error) {
	path := filepath.Join(baseDir, "config.json")
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, false, nil, nil
		}
		return nil, false, nil, newConfigErrorf("read config: %v", err)
	}
	marker, err := HasProfilesMarker(data)
	if err != nil {
		return nil, false, newConfigErrorf("parse legacy config: %v", err), nil
	}
	if !marker {
		return nil, false, nil, nil
	}
	cfg, err := ParseSingleConfig(data, baseDir)
	if err != nil {
		return nil, true, nil, err
	}
	return cfg, true, nil, nil
}

func defaultProfile(paths Paths) *Profile {
	return &Profile{
		Name:        DefaultProfileName,
		Dir:         paths.Dir,
		ConfigFile:  paths.Config,
		CookiesFile: paths.Cookies,
		ChatFile:    paths.Chat,
		AutoApprove: "off",
		Fingerprint: DefaultFingerprint,
		TLSEngine:   DefaultTLSEngine,
		Source:      SourceLegacy,
		Outbound:    OutboundRef{Kind: OutboundDirect, Type: "direct"},
	}
}

// migrateLegacyProfile loads one legacy profile strictly: wrong-typed
// settings are errors, not silent coercions. A missing config file
// yields defaults. It never writes. MIGRATE-ONLY: this is the sole
// reader of legacy files (through parseLegacyConfig strict mode and
// applyLegacy); LoadProfile refuses legacy files instead.
func migrateLegacyProfile(baseDir, name string, paths Paths) (*Profile, error) {
	data, err := os.ReadFile(paths.Config)
	if err != nil {
		if os.IsNotExist(err) {
			p := defaultProfile(paths)
			p.Name = name
			return p, nil
		}
		return nil, newConfigErrorf("profile %q: read config: %v", name, err)
	}
	s, err := parseLegacyConfig(data, true)
	if err != nil {
		return nil, err
	}
	return applyLegacy(name, paths, s, baseDir), nil
}

func migrateWarnings(p *Profile, write bool, generatedSet map[string]bool) []string {
	warnings := []string{}
	if _, err := os.Stat(p.CookiesFile); err != nil {
		warnings = append(warnings, "missing cookies file")
	}
	if generatedSet[p.Name] {
		warnings = append(warnings, "node_id generated")
	} else if !p.nodeIDPresent || p.NodeID == "" {
		if !write {
			warnings = append(warnings, "node_id will be generated on --write")
		}
	}
	return warnings
}

// generateNodeID returns 16 lowercase hex chars from crypto/rand
// (secrets.token_hex(8) equivalent).
func generateNodeID() (string, error) {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", newConfigErrorf("generate node_id: %v", err)
	}
	return hex.EncodeToString(b[:]), nil
}

// configsEqual compares two SingleConfigs by their canonical saved
// encoding (parsed-equal, ignoring file formatting).
func configsEqual(a, b *SingleConfig) (bool, error) {
	ab, err := canonicalSingleBytes(a)
	if err != nil {
		return false, err
	}
	bb, err := canonicalSingleBytes(b)
	if err != nil {
		return false, err
	}
	return string(ab) == string(bb), nil
}

func canonicalSingleBytes(cfg *SingleConfig) ([]byte, error) {
	if cfg.Profiles == nil {
		cfg.Profiles = make(map[string]*Profile)
	}
	root, err := buildSingleFileOrdered(cfg)
	if err != nil {
		return nil, err
	}
	return encodeOrderedJSONIndent(root, 2)
}

// interimDNSServerTag is the tag of the single server in the interim
// global dns section authored by authorInterimDNS.
const interimDNSServerTag = "castctl-doh"

// singleDNSDetour returns the one detour tag every profile in cfg
// routes through. A profile's detour tag is its outbound tag
// reference, its endpoint tag reference, or its inline outbound's
// tag — except when the resolved target is a direct outbound, which
// has no tag a detour can use: a direct-only profile carries no
// detour tag at all. The runtime "direct" outbound is synthesised at runtime
// (createOutbounds) and the synthetic "castctl-dialer" exists only
// for direct endpoint references; neither is a config tag, so
// neither can be a detour here (validateTagGraph would reject
// them as dangling, and sing-box rejects a detour to an empty
// direct outbound). When no single detour exists, the second
// return names the first profile in sorted order that has no
// detour tag or a different one, and ok is false. With no profiles
// at all there is nothing to route for: ("", "", false).
func singleDNSDetour(cfg *SingleConfig) (detour, refusing string, ok bool) {
	if cfg == nil || len(cfg.Profiles) == 0 {
		return "", "", false
	}
	for _, name := range cfg.ProfileNames() {
		p := cfg.Profiles[name]
		tag := detourTagForProfile(cfg, p)
		if detour == "" {
			if tag == "" {
				return "", name, false
			}
			detour = tag
			continue
		}
		if tag != detour {
			return "", name, false
		}
	}
	return detour, "", true
}

// detourTagForProfile returns the tag a dns detour for p would name,
// or "" when p is direct-only (no config tag exists for its outbound).
// A tag reference is resolved against cfg's outbounds, endpoints, and
// inline profile outbounds: when the resolved target is a direct
// outbound, "" is returned — a detour naming an empty direct outbound
// is runtime-invalid (sing-box refuses it), so no dns section may be
// authored for it. A tag that resolves to a selector/urltest outbound
// is returned as-is (its member list is not consulted); a tag that
// resolves to nothing is also returned as-is and left for
// validateTagGraph to reject as dangling.
func detourTagForProfile(cfg *SingleConfig, p *Profile) string {
	if p == nil {
		return ""
	}
	switch p.Outbound.Kind {
	case OutboundTag:
		if cfg != nil {
			for _, ob := range cfg.Outbounds {
				if ob.Tag == p.Outbound.Tag {
					if ob.Type == "direct" {
						return ""
					}
					return p.Outbound.Tag
				}
			}
			for _, ep := range cfg.Endpoints {
				if ep.Tag == p.Outbound.Tag {
					if ep.Type == "direct" {
						return ""
					}
					return p.Outbound.Tag
				}
			}
			for _, other := range cfg.Profiles {
				if other.Outbound.Kind == OutboundInline && other.Outbound.Tag == p.Outbound.Tag {
					if other.Outbound.Type == "direct" {
						return ""
					}
					return p.Outbound.Tag
				}
			}
		}
		return p.Outbound.Tag
	case OutboundInline:
		// An inline direct outbound is direct-only: its tag (if
		// any) names an empty direct outbound, which sing-box
		// refuses as a detour. Treat it as no detour.
		if p.Outbound.Type == "direct" {
			return ""
		}
		return p.Outbound.Tag
	default:
		return ""
	}
}

// authorInterimDNS authors the INTERIM global dns section onto
// candidate when the candidate has no dns section, the existing
// single file (when one exists) is otherwise identical to the
// candidate, and a single detour serves every profile. The authored
// section is the gated default only: one DoH server (https,
// IP-literal 1.1.1.1, no bootstrap hostname, path /dns-query)
// through the shared detour. It is global and single-profile-only
// by construction: the final model is a per-profile dns block
// (later PR), and this section is distributed into profile
// entries by `config migrate` there. Authoring is validated with
// the same checks a hand-written section faces (validateTagGraph
// plus the WireGuard key-sharing check); a validation failure
// falls back to no section with the refusal recorded, never to a
// written-but-invalid config. When candidate already carries a
// dns section, or differs from the existing file beyond dns, or
// no single detour exists, nothing is authored: the refusal is
// returned ("" when authoring was not applicable because a
// section already exists or the config differs).
func authorInterimDNS(candidate, existing *SingleConfig) (authored bool, refusal string) {
	if candidate == nil || candidate.DNS != nil || len(candidate.rawDNS) > 0 {
		return false, ""
	}
	if existing != nil {
		equal, err := configsEqual(stripDNS(existing), stripDNS(candidate))
		if err != nil || !equal {
			return false, ""
		}
	}
	detour, refusing, ok := singleDNSDetour(candidate)
	if !ok {
		if refusing == "" {
			return false, ""
		}
		return false, fmt.Sprintf("dns section not authored: profile %q does not share one detour tag with every other profile (direct-only, or a different outbound tag); add a shared outbound and re-run config migrate, or add a dns section by hand (see docs/config.md)", refusing)
	}
	detourJSON, err := json.Marshal(detour)
	if err != nil {
		return false, fmt.Sprintf("dns section not authored: cannot encode detour tag: %v", err)
	}
	raw := []byte(fmt.Sprintf(`{"servers":[{"tag":%q,"type":"https","server":"1.1.1.1","server_port":443,"path":"/dns-query","detour":%s}],"final":%q}`,
		interimDNSServerTag, detourJSON, interimDNSServerTag))
	dnsOpts, err := parseDNS(raw)
	if err != nil {
		return false, fmt.Sprintf("dns section not authored: %v", err)
	}
	candidate.DNS = dnsOpts
	candidate.rawDNS = raw
	if err := validateTagGraph(candidate); err != nil {
		candidate.DNS = nil
		candidate.rawDNS = nil
		return false, fmt.Sprintf("dns section not authored: %v", err)
	}
	if err := validateWireGuardPrivateKeys(candidate); err != nil {
		candidate.DNS = nil
		candidate.rawDNS = nil
		return false, fmt.Sprintf("dns section not authored: %v", err)
	}
	return true, ""
}

// stripDNS returns a shallow copy of cfg with no dns section, so
// configsEqual can compare two configs ignoring dns.
func stripDNS(cfg *SingleConfig) *SingleConfig {
	if cfg == nil {
		return nil
	}
	cp := *cfg
	cp.DNS = nil
	cp.rawDNS = nil
	return &cp
}

// cloned, outbound/endpoint lists and raw JSON slices are copied, so
// mutating the clone never affects the original.
func cloneSingleConfig(cfg *SingleConfig) *SingleConfig {
	if cfg == nil {
		return nil
	}
	out := *cfg
	out.Profiles = make(map[string]*Profile, len(cfg.Profiles))
	for name, p := range cfg.Profiles {
		out.Profiles[name] = p.clone()
	}
	out.Outbounds = slices.Clone(cfg.Outbounds)
	out.Endpoints = slices.Clone(cfg.Endpoints)
	out.rawOutbounds = copyRawList(cfg.rawOutbounds)
	out.rawEndpoints = copyRawList(cfg.rawEndpoints)
	if len(cfg.rawDNS) > 0 {
		out.rawDNS = append([]byte{}, cfg.rawDNS...)
	} else {
		out.rawDNS = nil
	}
	out.rawProfiles = make(map[string][]byte, len(cfg.rawProfiles))
	for name, raw := range cfg.rawProfiles {
		out.rawProfiles[name] = append([]byte{}, raw...)
	}
	if cfg.DNS != nil {
		dnsCopy := *cfg.DNS
		out.DNS = &dnsCopy
	}
	return &out
}

// singleFirstNames returns names with "default" first and the rest in
// their given (sorted) order, matching DiscoverProfileNames order.
func singleFirstNames(names []string) []string {
	out := make([]string, 0, len(names))
	for _, n := range names {
		if n == DefaultProfileName {
			out = append(out, n)
		}
	}
	for _, n := range names {
		if n != DefaultProfileName {
			out = append(out, n)
		}
	}
	return out
}
